import { promises as fs } from 'fs';
import path from 'path';
import { getMergedConfigParsedLines, extractDirectivesAndBody, mergeFlatDirectives, stringifyParsedLines } from './abcConfig.js';

/**
 * Recursively scans a directory for files matching *.raw.abc
 */
export async function findRawAbcFiles(dir: string): Promise<string[]> {
  let results: string[] = [];
  const entries = await fs.readdir(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results = results.concat(await findRawAbcFiles(fullPath));
    } else if (entry.isFile() && entry.name.endsWith('.raw.abc')) {
      results.push(fullPath);
    }
  }
  return results;
}

// Utility: Group files by their directory
function groupFilesByDirectory(files: string[]): Map<string, string[]> {
  const dirToFiles = new Map<string, string[]>();
  for (const file of files) {
    const dir = path.dirname(file);
    if (!dirToFiles.has(dir)) dirToFiles.set(dir, []);
    dirToFiles.get(dir)!.push(file);
  }
  return dirToFiles;
}

/**
 * Assembles a .raw.abc file with merged configs and writes to output
 * @param rawFile Path to the .raw.abc file
 * @param sourceRoot Root directory for source files
 * @param outRoot Output directory
 * @param preMergedConfig Optional: pre-merged config lines for the file's directory
 */
export async function assembleRawAbc(
  rawFile: string,
  sourceRoot: string,
  outRoot: string,
  preMergedConfig?: ReturnType<typeof getMergedConfigParsedLines>
) {
  const fileDir = path.dirname(rawFile);
  const mergedConfigLines = preMergedConfig ?? getMergedConfigParsedLines(sourceRoot, fileDir);
  const rawContent = await fs.readFile(rawFile, 'utf8');
  const { directives: abcDirectives, body, lineEnding } = extractDirectivesAndBody(rawContent);
  const finalDirectives = mergeFlatDirectives([...mergedConfigLines], abcDirectives);
  const header = `% Generated by abctools on ${new Date().toISOString()}${lineEnding}`;
  const outContent = `${header}${stringifyParsedLines(finalDirectives, lineEnding)}${lineEnding}${lineEnding}${body}`;
  const relPath = path.relative(sourceRoot, rawFile).replace(/\.raw\.abc$/, '.abc');
  const outPath = path.join(outRoot, relPath);
  await fs.mkdir(path.dirname(outPath), { recursive: true });

  // Only write if content has changed (ignoring the header line)
  let shouldWrite = true;
  try {
    const existing = await fs.readFile(outPath, 'utf8');
    // Remove the header line (first line) from both contents for comparison
    const stripHeader = (content: string) => content.replace(/^% Generated by abctools.*\r?\n/, '');
    shouldWrite = stripHeader(existing) !== stripHeader(outContent);
  } catch {
    // File does not exist, so we should write
    shouldWrite = true;
  }
  if (shouldWrite) {
    await fs.writeFile(outPath, outContent, 'utf8');
  }
}

/**
 * Main build function: finds all .raw.abc files, merges configs per directory, and assembles outputs
 */
export async function build(sourceRoot: string, outRoot: string) {
  const files = await findRawAbcFiles(sourceRoot);
  const dirToFiles = groupFilesByDirectory(files);
  for (const [dir, filesInDir] of dirToFiles.entries()) {
    const mergedConfig = getMergedConfigParsedLines(sourceRoot, dir);
    for (const file of filesInDir) {
      await assembleRawAbc(file, sourceRoot, outRoot, mergedConfig);
    }
  }
}
